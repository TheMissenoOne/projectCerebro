const wikiPages = window.wikiPages || {};

function loadWikiPage(slug) {
  return wikiPages[slug] || wikiPages.index;
}

function showARTableType(type) {
  document.querySelectorAll('.ar-type-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.type === type);
  });
  renderActionTable();
}

function showARMode(mode) {
  document.querySelectorAll('.ar-mode-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.mode === mode);
  });
  
  const descEl = document.getElementById('ar-mode-desc');
  if (descEl) {
    const modes = {
      'temp': 'Modo Temporário: dificuldade normal (coluna = obstáculo)',
      'persist': 'Modo Indefinido: coluna + 1 (dificuldade aumenta)',
      'perm': 'Modo Permanente: coluna + 3 (dificuldade aumenta muito)'
    };
    descEl.textContent = modes[mode] || modes['temp'];
  }
  
  renderActionTable();
}

function renderActionTable() {
  const table = document.getElementById('action-table');
  if (!table) return;
  
  const typeBtn = document.querySelector('.ar-type-btn.active');
  const modeBtn = document.querySelector('.ar-mode-btn.active');
  
  const type = typeBtn ? typeBtn.dataset.type : 'avov';
  const mode = modeBtn ? modeBtn.dataset.mode : 'temp';
  
  const modeShift = { 'temp': 0, 'persist': 1, 'perm': 3 }[mode];
  
  const data = type === 'avov' ? AVOV_DATA : EVRV_DATA;
  
  let html = '<thead><tr><th>AV\\OV</th>';
  for (let ov = -9; ov <= 15; ov++) {
    html += `<th>${ov}</th>`;
  }
  html += '</tr></thead><tbody>';
  
  for (let av = 15; av >= -9; av--) {
    html += `<tr><td>${av}</td>`;
    for (let ov = -9; ov <= 15; ov++) {
      const ovShifted = Math.max(-9, Math.min(15, ov + modeShift));
      const result = data[av + 9]?.[ovShifted + 9] || '-';
      const isSpecial = result === 'N' || result === 'F' || result === 'A' || result === 'S';
      html += `<td class="${isSpecial ? 'result-special' : ''}">${result}</td>`;
    }
    html += '</tr>';
  }
  html += '</tbody>';
  
  table.innerHTML = html;
}

