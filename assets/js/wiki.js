function renderActionTable() {
  const table = document.getElementById('action-table');
  if (!table) return;
  
  const typeBtn = document.querySelector('.ar-type-btn.active');
  const modeBtn = document.querySelector('.ar-mode-btn.active');
  
  const type = typeBtn ? typeBtn.dataset.type : 'avov';
  const mode = modeBtn ? modeBtn.dataset.mode : 'temp';
  
  const modeShift = { 'temp': 0, 'persist': -1, 'perm': -3 }[mode];
  
  const data = type === 'avov' ? AVOV_DATA : EVRV_DATA;
  
  let rows, cols, rowStart, colStart;
  if (type === 'avov') {
    rows = 50;
    cols = 52;
    rowStart = 1;
    colStart = 1;
  } else {
    rows = 52;
    cols = 52;
    rowStart = 1;
    colStart = 1;
  }
  
  let html = '<thead><tr><th>' + (type === 'avov' ? 'AV\\OV' : 'EV\\RV') + '</th>';
  for (let c = colStart; c < colStart + cols; c++) {
    html += `<th>${c}</th>`;
  }
  html += '</tr></thead><tbody>';
  
  for (let r = 0; r < rows; r++) {
    const av = rowStart + r;
    html += `<tr><td>${av}</td>`;
    
    for (let c = 0; c < cols; c++) {
      const colIndex = c + modeShift;
      
      let result = '-';
      if (colIndex >= 0 && colIndex < data[r].length) {
        result = data[r][colIndex];
      } else if (colIndex < 0) {
        result = 'N';
      }
      
      const isSpecial = result === 'N' || result === 'F' || result === 'A' || result === 'S';
      html += `<td class="${isSpecial ? 'result-special' : ''}">${result}</td>`;
    }
    html += '</tr>';
  }
  html += '</tbody>';
  
  table.innerHTML = html;
}

function showARTableType(type) {
  document.querySelectorAll('.ar-type-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.type === type);
  });
  renderActionTable();
}

